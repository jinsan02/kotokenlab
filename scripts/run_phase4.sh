#!/bin/sh
# Phase 4 — 오늘의 부정 결과를 두 축으로 따라간다.
#
# 오늘 결론 (reports/tables/cpt_main.md)
#   같은 원문 168.5MB 에서 T2b 는 한국어 BPB 1.5671, C0 는 1.1375 다.
#   압축은 약속대로 됐지만(토큰 30.2% 감소) 언어모델이 못 따라왔다.
#   진단: 새 토큰 30,000개의 **중앙값 발화가 168.5MB 전체에서 143회** 다.
#   43%의 토큰이 새 토큰인데도 그렇다 — 소수 머리가 다 먹는다.
#   초기화가 나쁜 게 아니라 노출이 희박한 것이다.
#
# 그래서 두 축을 본다: 노출을 늘리거나(1), 나눠 가질 입을 줄이거나(2).
set -e
cd /c/llm_tokenizer
P=./.conda/python.exe

########################################################################
# 1. Equal Token Budget (스펙 §32~33) — 사전 등록된 미완 질문
#
# 오늘은 같은 **원문** 을 봤다. 여기서는 같은 **토큰수** 를 준다.
# 실무에서 토크나이저를 바꾸는 이유가 이것이다 — 같은 문맥·같은 연산으로
# 더 많은 원문을 넣는 것. T2b 에게 가장 유리한 틀이다.
#
# C0 와 T2a 는 이미 정확히 49,922,048 토큰을 봤다. **T2b 만 다시 돌리면 된다.**
# 실측 0.206718 tok/B 로 역산해 241,498,793 B 를 준다. 토큰 목표는 근사이므로
# 끝난 뒤 tokens_seen 을 확인하고 실제값을 보고한다.
#
# LR 스케줄은 바이트 기준 코사인인데, 조건마다 tok/B 가 일정하므로
# '토큰 진행률 대비 LR' 곡선은 C0 와 같은 모양이 된다.
#
# 사전 등록 예측: 닫히지 않는다. 20MB->168.5MB (8.4배) 가 1.74->1.57 로 0.18 을
# 메웠으니, 168.5->241.5MB (1.43배) 는 0.02 안팎이다. 최종 1.55 근처, C0 와
# 여전히 0.41 차이. **이 예측이 틀리면 그게 더 중요한 발견이다.**
########################################################################
echo "########## 1. Equal Token Budget — T2b ##########"
$P -m src.training.cpt --model artifacts/models/kot2b_v2_n30000_mean \
   --name t2b_mean --seed 42 --budget-bytes 241498793 --pool-docs 70000 \
   --eval-bytes 20000000 --eval-budget 2000000 --tag eqtok --save

########################################################################
# 2. N 스윕 — 압축과 학습가능성의 경계는 어디인가
#
# N=10,000 은 압축의 83% 를 낸다 (-25.2% vs -30.2%, t2_sweep.md).
# 새 토큰이 1/3 이므로 토큰당 노출은 약 3배 — 중앙값 143 -> 약 430 회.
# 노출이 원인이라는 진단이 맞다면 격차가 눈에 띄게 줄어야 한다.
#
# 예산·풀·시드는 오늘과 **동일** 하게 둔다. 그래야 오늘의 C0/T2a/T2b(N=30k)
# 와 한 표에 놓을 수 있다.
#
# 사전 등록 예측: 격차가 줄지만 C0 를 넘지는 못한다. 넘으면 "압축과
# 학습가능성 사이에 최적 N 이 있다" 는 새 주장이 성립한다.
########################################################################
echo "########## 2. N=10,000 수술 ##########"
$P scripts/run_surgery.py --tokenizer kot2b_v2_n10000 --init mean --seed 42

echo "########## 2. N=10,000 CPT (오늘과 동일 조건) ##########"
$P -m src.training.cpt --model artifacts/models/kot2b_v2_n10000_mean \
   --name t2b10k_mean --seed 42 --budget-bytes 168500000 --pool-docs 50000 \
   --eval-bytes 20000000 --eval-budget 2000000 --tag main --save

########################################################################
# 3. N=10,000 의 노이즈 플로어 — 새 조건에는 자기 sigma 가 필요하다
#
# RULES 는 "조건이 늘어나면 그 조건의 sigma 를 따로 재고, 재지 않았으면
# 구별 불가로 남긴다" 고 못박는다. N=10,000 은 새 조건이다.
#
# T2b(N=30,000)의 sigma 0.001234 를 보수적 상한으로 쓸 수도 있다 — 손상이
# 덜한 조건이니 실제 sigma 는 그보다 작을 것이고, 큰 sigma 를 쓰면 차이를
# 덜 검출하는 쪽으로만 틀린다. 다만 33분이면 실측할 수 있으므로 실측한다.
#
# 조건은 노이즈 플로어와 동일하게 17.5MB (reports/tables/noise_floor.md).
########################################################################
echo "########## 3. N=10,000 노이즈 플로어 (3 seed) ##########"
for S in 42 123 2026; do
  $P -m src.training.cpt --model artifacts/models/kot2b_v2_n10000_mean \
     --name t2b10k_mean --seed $S --budget-bytes 17500000 --pool-docs 5000 \
     --tag noise
done

echo "########## PHASE 4 DONE ##########"
